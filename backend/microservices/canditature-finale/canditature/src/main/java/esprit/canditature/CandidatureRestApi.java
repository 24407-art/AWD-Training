package esprit.canditature;

import esprit.canditature.dto.Candidate;
import esprit.canditature.dto.CandidatureResponse;
import esprit.canditature.dto.JobResponse;
import esprit.canditature.entity.Candidature;
import esprit.canditature.feignClient.CandidatClient;
import esprit.canditature.feignClient.JobClient;
import esprit.canditature.service.CandidatureService;
import feign.FeignException;
import feign.codec.DecodeException;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.*;

import java.util.List;

@RestController
@RequestMapping("/mic3/candidature")
public class CandidatureRestApi {

    private final CandidatClient candidatClient;
    private final JobClient jobClient;
    private final CandidatureService candidatureService;

    // Constructor injection: Spring gives the proxies generated by @EnableFeignClients
    public CandidatureRestApi(CandidatClient candidatClient, JobClient jobClient, CandidatureService candidatureService) {
        this.candidatClient = candidatClient;
        this.jobClient = jobClient;
        this.candidatureService = candidatureService;
    }

    @GetMapping("/hello")
    public String sayHello() {
        return "Hello Im microservice 3!";
    }

    /**
     * GET http://localhost:8085/mic3/candidature/candidat/1
     * candidature -> (Eureka: where is CANDIDAT?) -> GET http://<instance>/mic1/candidates/1
     */
    @GetMapping("/candidat/{id}")
    public Candidate getCandidat(@PathVariable("id") Long id) {
        return candidatClient.findById(id);
    }

    @GetMapping("/job/{id}")
    public JobResponse getJob(@PathVariable("id") Long id) {
        return jobClient.findById(id);
    }

    // ------------------------------------------------------------------ candidatures

    /**
     * POST http://localhost:8085/mic3/candidature
     * {"candidateId": 1, "jobId": 1, "motivation": "Je souhaite rejoindre l'équipe"}
     * -> 201 + the candidature with the candidate and the job
     */
    @PostMapping
    public ResponseEntity<CandidatureResponse> addCandidature(@RequestBody Candidature candidature) {
        return ResponseEntity.status(HttpStatus.CREATED).body(candidatureService.add(candidature));
    }

    /** GET http://localhost:8085/mic3/candidature/1 -> candidature + candidate + job */
    @GetMapping("/{id}")
    public CandidatureResponse getCandidature(@PathVariable("id") Long id) {
        return candidatureService.getById(id);
    }

    @GetMapping
    public List<CandidatureResponse> getAllCandidatures() {
        return candidatureService.getAll();
    }

    @DeleteMapping("/{id}")
    public ResponseEntity<Void> deleteCandidature(@PathVariable("id") Long id) {
        candidatureService.delete(id);
        return ResponseEntity.noContent().build();
    }

    // ------------------------------------------------------------------ errors of the Feign calls

    // candidat or job answered 404 -> Feign throws FeignException.NotFound -> we return 404 too (instead of 500)
    @ExceptionHandler(FeignException.NotFound.class)
    public ResponseEntity<String> remoteNotFound(FeignException.NotFound e) {
        return ResponseEntity.status(HttpStatus.NOT_FOUND).body("Candidat ou job introuvable : " + e.getMessage());
    }

    // the remote service answered, but its JSON could not be converted into our DTO -> 502
    @ExceptionHandler(DecodeException.class)
    public ResponseEntity<String> remoteUnreadable(DecodeException e) {
        return ResponseEntity.status(HttpStatus.BAD_GATEWAY)
                .body("Réponse illisible : " + e.getMessage());
    }

    // CANDIDAT or JOB stopped or not registered in Eureka -> 503 Service Unavailable
    @ExceptionHandler(FeignException.class)
    public ResponseEntity<String> remoteUnavailable(FeignException e) {
        return ResponseEntity.status(HttpStatus.SERVICE_UNAVAILABLE)
                .body("Microservice CANDIDAT ou JOB indisponible : " + e.getMessage());
    }
}
